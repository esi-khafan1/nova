const {PGlite}=require('@electric-sql/pglite');
const {readFileSync}=require('node:fs');
const {randomUUID}=require('node:crypto');
const assert=require('node:assert/strict');
(async()=>{
 const db=new PGlite();
 const id=Object.fromEntries(['student','other','counselor','former','admin'].map(name=>[name,randomUUID()]));
 await db.exec(`
  create role authenticated;create role anon;create schema auth;create schema private;
  create type public.app_role as enum('student','counselor','admin');
  create table public.profiles(id uuid primary key,role public.app_role,registration_status text);
  create table public.counselor_students(student_id uuid,counselor_id uuid);
  create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  create function private.current_user_role() returns public.app_role language sql stable security definer set search_path='' as $$select role from public.profiles where id=auth.uid()$$;
  create function private.student_services_active(target_student_id uuid) returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.profiles where id=target_student_id and role='student' and registration_status='active')$$;
  create function private.counselor_currently_assigned(target_student_id uuid) returns boolean language sql stable security definer set search_path='' as $$select private.current_user_role()='counselor' and private.student_services_active(target_student_id) and exists(select 1 from public.counselor_students where student_id=target_student_id and counselor_id=auth.uid())$$;
  grant usage on schema public,private,auth to authenticated;
  grant select on public.profiles to authenticated;
 `);
 await db.query("insert into public.profiles values ($1,'student','active'),($2,'student','active'),($3,'counselor','active'),($4,'counselor','active'),($5,'admin','active')",[id.student,id.other,id.counselor,id.former,id.admin]);
 await db.query('insert into public.counselor_students values ($1,$2)',[id.student,id.counselor]);
 await db.exec(readFileSync('supabase/migrations/099_student_daily_report_notes.sql','utf8'));
 const actor=async name=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id[name]]);await db.exec('set role authenticated');};
 const save=(day,note)=>db.query('select public.save_student_daily_note($1,$2)',[day,note]);
 const read=async()=>(await db.query('select student_id,day::text,note from public.student_daily_notes order by day')).rows;
 await actor('student');
 await assert.rejects(save('2999-01-01','future'),/Only past and current/);
 await assert.rejects(save('2019-01-01','older'),/Only past and current/);
 await assert.rejects(save('2020-01-01','x'.repeat(2001)),/Invalid daily note/);
 await assert.rejects(db.query('insert into public.student_daily_notes values ($1,$2,$3)',[id.student,'2020-01-01','bypass']),/permission denied/);
 await save('2020-01-01','   مشاور، امروز تمرین را عقب انداختم.  ');
 assert.equal((await read())[0].note,'مشاور، امروز تمرین را عقب انداختم.');
 await save('2020-01-01','یادداشت اصلاح‌شده');
 assert.equal((await read()).length,1);
 await actor('other');assert.equal((await read()).length,0);
 await actor('counselor');assert.equal((await read())[0].note,'یادداشت اصلاح‌شده');
 await assert.rejects(save('2020-01-01','نباید تغییر کند'),/Active student required/);
 await actor('former');assert.equal((await read()).length,0);
 await actor('admin');assert.equal((await read()).length,0);
 await db.exec('reset role');
 await db.query("update public.profiles set registration_status='disabled' where id=$1",[id.student]);
 await actor('student');assert.equal((await read()).length,0);
 await assert.rejects(save('2020-01-01','disabled'),/Active student required/);
 await actor('counselor');assert.equal((await read()).length,0);
 await db.exec('reset role');
 await db.query("update public.profiles set registration_status='active' where id=$1",[id.student]);
 await db.query('delete from public.counselor_students where student_id=$1',[id.student]);
 await db.query('insert into public.counselor_students values($1,$2)',[id.student,id.former]);
 await actor('counselor');assert.equal((await read()).length,0);
 await actor('former');assert.equal((await read()).length,1);
 await actor('student');await save('2020-01-01','  ');assert.equal((await read()).length,0);
 await db.exec('reset role;set role anon');
 await assert.rejects(db.query('select * from public.student_daily_notes'),/permission denied/);
 await assert.rejects(save('2020-01-01','anon'),/permission denied/);
 await db.close();
 console.log('PASS: daily notes per day, student-only writes, current-counselor reads, disabled/old counselor isolation, validation and clearing');
})().catch(error=>{console.error(error);process.exitCode=1});
