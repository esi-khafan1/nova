import assert from "node:assert/strict";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { readFileSync } from "node:fs";
import { StudentExamCard, type StudentExam, type StudentExamAttempt } from "../components/dashboard/student-exam-card";

const now = new Date("2026-10-15T10:00:00Z");
const exam: StudentExam = { id: "exam-test", title: "آزمون آزمایشی", description: "راهنمای آزمون بدون حذف", mode: "booklet", audience: "selected", starts_at: "2026-10-15T09:30:00Z", start_window_ends_at: null, duration_minutes: 60, created_at: "2026-10-01T00:00:00Z", exam_booklets: [{ id: "one", question_count: 40 }, { id: "two", question_count: 65 }] };
const attempt: StudentExamAttempt = { exam_id: exam.id, score: -3.33, correct_answers: 10, total_questions: 105, submitted_at: "2026-10-15T09:50:00Z" };
const render = (patch: Partial<StudentExam> = {}, done?: StudentExamAttempt, expires?: string) => renderToStaticMarkup(createElement(StudentExamCard, { exam: { ...exam, ...patch }, attempt: done, session: expires ? { exam_id: exam.id, expires_at: expires } : undefined, now }));
const active = render();
for (const text of ["آزمون دفترچه‌ای کنکوری", "آزمون آزمایشی", "راهنمای آزمون بدون حذف", "۲ دفترچه", "۱۰۵ سؤال", "ورود به آزمون و شروع", 'href="/dashboard/student/exams/exam-test"']) assert.ok(active.includes(text), text);
assert.ok(render({ starts_at: "2026-10-16T09:00:00Z" }).includes("آزمون هنوز شروع نشده است."));
assert.ok(render({ starts_at: "2026-10-14T09:00:00Z" }).includes("مهلت شرکت در آزمون تمام شده است."));
const pendingReview = render({}, attempt);
assert.ok(pendingReview.includes("مشاهدهٔ وضعیت ثبت آزمون"));
assert.ok(!pendingReview.includes("درصد کنکوری:"));
const review = render({ starts_at: "2026-10-14T09:00:00Z" }, attempt);
assert.ok(review.includes("بررسی دفترچه و پاسخ‌برگ"));
assert.ok(review.includes("#exam-review"));
assert.ok(review.includes("درصد کنکوری: -۳.۳۳٪"));
assert.ok(!render({ starts_at: "2026-10-14T09:00:00Z" }, { ...attempt, score: null }).includes("درصد کنکوری:"));
assert.ok(render({ starts_at: "2026-10-14T09:00:00Z" }, { ...attempt, score: 0 }).includes("درصد کنکوری: ۰٪"));
const floating = { start_window_ends_at: "2026-10-15T12:00:00Z" };
assert.ok(render(floating).includes("مشاهده و شروع آزمون"));
assert.ok(render(floating, undefined, "2026-10-15T11:00:00Z").includes("ادامهٔ آزمون"));
assert.ok(render(floating, undefined, "2026-10-15T09:59:00Z").includes("ثبت پاسخ‌های ذخیره‌شده"));
assert.ok(render({ ...floating, starts_at: "2026-10-16T09:00:00Z", start_window_ends_at: "2026-10-16T12:00:00Z" }).includes("بازهٔ شروع هنوز باز نشده است."));
assert.ok(render({ ...floating, start_window_ends_at: "2026-10-15T09:59:00Z" }).includes("مهلت شروع آزمون تمام شده است."));
// A floating attempt stays unrevealed until the GLOBAL review window ends.
assert.ok(!render(floating, attempt).includes("درصد کنکوری:"));
assert.ok(render({ ...floating, start_window_ends_at: "2026-10-15T08:00:00Z", starts_at: "2026-10-15T07:00:00Z" }, attempt).includes("درصد کنکوری:"));
const read = (p: string) => readFileSync(p, "utf8");
const shell = read("components/dashboard/dashboard-shell.tsx");
const designer = shell.slice(shell.indexOf('if (role === "exam_designer")'), shell.indexOf('const isStudentFocus'));
assert.ok(designer.includes("<LandingHeader isAuthenticated examDesignerPanel"));
assert.ok(!designer.includes("<aside") && !designer.includes("<Logo"));
assert.ok(!designer.includes("ed-workspace-links"));
for (const text of ["{name ||", "{labels[role]}", "signOut", "خروج از حساب", "مشاهده سایت"]) assert.ok(designer.includes(text), text);
const header = read("components/landing-header.tsx");
assert.ok(header.includes('examDesignerPanel ? "/dashboard/exam_designer"'));
assert.ok(header.includes("examDesignerPanel ? examDesignerItems"));
const css = read("app/exam-panel-refresh.css");
assert.ok(css.includes(".student-exams-page{background:#fff"));
assert.ok(css.includes(".exam-designer-portal"));
assert.ok(!css.includes("display:none"));
console.log("Exam refresh: fixed/floating actions, review privacy, scores, navbar tools and scoped white/ice theme passed.");
