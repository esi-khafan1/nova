// Pure planner operations only; no production data or account is used.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const path = require('node:path');
const filename = path.join(process.cwd(), 'virtual-planner-grid.cjs');
const mod = new Module(filename, module);
mod.filename = filename;
mod.paths = Module._nodeModulePaths(process.cwd());
mod._compile(ts.transpileModule(fs.readFileSync('lib/planner-grid.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { emptyPlannerGrid, movePlannerBlock, copyPlannerBlock, applyPlannerTemplate, summarizePlannerGrid, reviewsForWeek } = mod.exports;
const block = (key, day, overrides = {}) => ({ key, id: `db-${key}`, dayOfWeek: day, subject: 'زیست', chapter: 'فصل ۱', activityType: 'lesson', durationMinutes: 90, targetTestCount: null, details: '', topics: [{title:'گفتار یک', pageStart:1, pageEnd:4}], ...overrides });
const grid = emptyPlannerGrid();
const a = block('a', 0, {targetTestCount: 20, linkedExamId: 'exam-id'});
const b = block('b', 1, {subject:'شیمی', durationMinutes:45, targetTestCount:15});
const c = block('c', 1, {subject:'فیزیک', durationMinutes:60});
grid[0] = [a]; grid[1] = [b,c];
const saved = JSON.stringify(grid);
const moved = movePlannerBlock(grid,{day:0,index:0},{day:1,index:1});
assert.equal(JSON.stringify(grid),saved, 'move is immutable');
assert.deepEqual(moved[1].map(x=>x.key),['b','a','c']);
assert.equal(moved[1][1].dayOfWeek,1);assert.equal(moved[1][1].id,'db-a');assert.equal(moved[1][1].linkedExamId,'exam-id');
const reordered = movePlannerBlock(moved,{day:1,index:0},{day:1,index:3});
assert.deepEqual(reordered[1].map(x=>x.key),['a','c','b']);
assert.throws(()=>movePlannerBlock([[block('p',0,{completed:true})],...emptyPlannerGrid().slice(1)],{day:0,index:0},{day:1,index:0}),/Protected/);
assert.throws(()=>movePlannerBlock(grid,{day:8,index:0},{day:1,index:0}),/Invalid/);
const copied = copyPlannerBlock({...a,completed:true,locked:true}, 2, 'copy-a');
assert.equal(copied.id,null);assert.equal(copied.linkedExamId,null);assert.equal(copied.completed,false);assert.equal(copied.locked,false);assert.equal(copied.dayOfWeek,2);
copied.topics[0].title='متن دیگر';assert.equal(a.topics[0].title,'گفتار یک');assert.throws(()=>copyPlannerBlock(a,2,'a'),/new key/);
const template = emptyPlannerGrid();template[0] = [block('t1',0),block('t2',0),null,block('t3',0,{linkedExamId:'x'})];template[1]=[block('t4',1)];
let sequence=0;const keys=()=>`new-${++sequence}`;
const filled = applyPlannerTemplate(grid,template,'empty',keys);
assert.deepEqual(filled[0].map(x=>x?.key??null),['a','new-1',null,'new-2']);assert.equal(filled[1][0].key,'b');
assert.equal(filled[0][3].id,null);assert.equal(filled[0][3].linkedExamId,null);assert.equal(JSON.stringify(grid),saved);
const replaced = applyPlannerTemplate(grid,template,'replace',keys);
assert.equal(replaced[0][0].subject,'زیست');assert.equal(replaced[1].length,1);assert.equal(replaced[1][0].key,'new-6');
assert.throws(()=>applyPlannerTemplate([[block('done',0,{completed:true})],...emptyPlannerGrid().slice(1)],template,'replace',keys),/Protected/);
assert.throws(()=>applyPlannerTemplate(grid,template,'empty',()=> 'a'),/Duplicate/);
const totals = summarizePlannerGrid(grid);
assert.deepEqual({minutes:totals.minutes,tests:totals.tests,blocks:totals.blocks,slots:totals.slots,empty:totals.emptySlots},{minutes:195,tests:35,blocks:3,slots:35,empty:32});
assert.equal(totals.days[1].minutes,105);assert.deepEqual(totals.subjects.find(x=>x.subject==='زیست'),{subject:'زیست',minutes:90,tests:20,blocks:1});
const full=emptyPlannerGrid();full[0]=Array.from({length:6},(_,i)=>block(`k${i}`,0));assert.equal(summarizePlannerGrid(full).slots,42);
assert.throws(()=>summarizePlannerGrid([[block('x',0,{durationMinutes:-1})],...emptyPlannerGrid().slice(1)]),/Invalid/);
const sources=[{weekStart:'2026-12-26',blocks:[block('before',6),block('exam',6,{activityType:'exam'}),block('makeup',6,{activityType:'makeup'})]},{weekStart:'2027-01-02',blocks:[block('now',0),block('later',5)]}];
const review=reviewsForWeek('2027-01-02',sources);
assert.deepEqual(review.filter(x=>x.blockKey==='before').map(x=>[x.date,x.offset]),[['2027-01-02',1],['2027-01-04',3],['2027-01-08',7]]);
assert.deepEqual(review.filter(x=>x.blockKey==='now').map(x=>[x.date,x.offset]),[['2027-01-03',1],['2027-01-05',3]]);
assert.deepEqual(review.filter(x=>x.blockKey==='later').map(x=>x.date),['2027-01-08']);
assert.equal(review.some(x=>x.blockKey==='exam'||x.blockKey==='makeup'),false);
assert.deepEqual(reviewsForWeek('2027-01-09',sources).filter(x=>x.blockKey==='now').map(x=>[x.date,x.offset]),[['2027-01-09',7]]);
assert.throws(()=>reviewsForWeek('2027-02-30',sources),/Invalid date/);
console.log('PASS: immutable move/copy, protected boxes, safe template copying, totals and dated cross-week reviews');
