const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
const migration = fs.readFileSync('supabase/migrations/096_designer_exam_attempt_review.sql', 'utf8').replace(/^notify .*$/gim, '');
const designer = '11111111-1111-4111-8111-111111111111';
const otherDesigner = '22222222-2222-4222-8222-222222222222';
const student = '33333333-3333-4333-8333-333333333333';
const otherStudent = '44444444-4444-4444-8444-444444444444';
const exam = '55555555-5555-4555-8555-555555555555';
const attempt = '66666666-6666-4666-8666-666666666666';
const quote = value => `'${value}'::uuid`;
(async () => {
 const db = new PGlite();
 await db.exec(`create role authenticated; create role anon; create schema auth; create schema private;
 create type public.app_role as enum('student','exam_designer');
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create table public.profiles(id uuid primary key,role public.app_role,full_name text);
 create function private.current_user_role() returns public.app_role language sql stable security definer set search_path='' as $$select p.role from public.profiles p where p.id=(select auth.uid())$$;
 create table public.exams(id uuid primary key,counselor_id uuid,mode text);
 create table public.exam_attempts(id uuid primary key,exam_id uuid,student_id uuid,score numeric,correct_answers smallint,incorrect_answers smallint,unanswered_count smallint,total_questions smallint,submitted_at timestamptz,answers jsonb);
 create table public.exam_booklets(id uuid primary key,exam_id uuid,title text,pdf_url text,explanation_pdf_url text,sort_order smallint,start_question_number smallint,end_question_number smallint,key_answers jsonb);
 grant usage on schema public,private,auth to authenticated;
 insert into public.profiles values (${quote(designer)},'exam_designer','طراح'),(${quote(otherDesigner)},'exam_designer','طراح دیگر'),(${quote(student)},'student','دانش‌آموز یک'),(${quote(otherStudent)},'student','دانش‌آموز دو');
 insert into public.exams values (${quote(exam)},${quote(designer)},'booklet');
 insert into public.exam_attempts values (${quote(attempt)},${quote(exam)},${quote(student)},50,1,1,1,3,now(),'{"1":1,"2":3}');
 insert into public.exam_booklets values ('77777777-7777-4777-8777-777777777777',${quote(exam)},'دفترچه','https://example.invalid/questions.pdf',null,0,1,3,'{"1":1,"2":2,"3":4}');`);
 await db.exec(migration);
 const claim = async id => db.exec(`select set_config('request.jwt.claim.sub',${quote(id)}::text,false)`);
 await claim(designer);
 await db.exec('set role authenticated');
 const rows = (await db.query(`select * from public.designer_exam_attempts(${quote(exam)})`)).rows;
 assert.equal(rows.length, 1);
 assert.equal(rows[0].student_name, 'دانش‌آموز یک');
 const review = (await db.query(`select question_number,student_choice,correct_choice,answer_status from public.designer_exam_attempt_review(${quote(exam)},${quote(attempt)})`)).rows;
 assert.deepEqual(review.map(r=>r.answer_status),['correct','incorrect','unanswered']);
 assert.deepEqual(review.map(r=>r.student_choice),[1,3,null]);
 await assert.rejects(db.query(`select * from public.designer_exam_attempt_review(${quote(exam)},${quote(otherStudent)})`), /Submitted attempt not found/);
 await claim(otherDesigner);
 await assert.rejects(db.query(`select * from public.designer_exam_attempts(${quote(exam)})`), /Exam not found/);
 await assert.rejects(db.query(`select * from public.designer_exam_attempt_review(${quote(exam)},${quote(attempt)})`), /Submitted attempt not found/);
 await claim(otherStudent);
 await assert.rejects(db.query(`select * from public.designer_exam_attempts(${quote(exam)})`), /Exam not found/);
 await db.exec('reset role');
 await db.close();
 const page = fs.readFileSync('app/dashboard/exam_designer/[id]/attempts/[attemptId]/page.tsx','utf8');
 assert.match(page,/requireProfile\(\["exam_designer"\]\)/);
 assert.match(page,/\.eq\("counselor_id", profile\.id\)/);
 assert.match(page,/StudentExamReview questions=\{review as ExamReviewQuestion\[\]\}/);
 console.log('Designer sees only own submitted participants and the student-style, per-question answer sheet; foreign roles denied.');
})().catch(error=>{ console.error(error); process.exitCode=1; });
