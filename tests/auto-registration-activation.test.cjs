const { PGlite } = require('@electric-sql/pglite');
const { readFileSync } = require('node:fs');
const { randomUUID } = require('node:crypto');
const assert = require('node:assert/strict');

(async () => {
  const db = new PGlite();
  const ids = Object.fromEntries(['admin','counselor','unapproved','withReceipt','manual','missingReceipt','unverified','active','otherStudent','otherCounselor'].map(key=>[key,randomUUID()]));
  await db.exec(`
    create role authenticated; create role anon; create schema auth; create schema private; create schema storage;
    create type public.app_role as enum ('admin','counselor','student');
    create table public.profiles(id uuid primary key,role public.app_role,registration_status text);
    create table public.counselor_profiles(user_id uuid primary key,approval_status text);
    create table public.counselor_students(counselor_id uuid,student_id uuid);
    create table public.student_registrations(student_id uuid primary key,receipt_path text,approved_at timestamptz,approved_by uuid);
    create table public.student_account_details(student_id uuid primary key);
    create table public.student_manual_activations(student_id uuid,activated_by uuid,counselor_id uuid,previous_status text);
    create table auth.users(id uuid primary key,email_confirmed_at timestamptz,phone_confirmed_at timestamptz);
    create table storage.objects(bucket_id text,name text);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create function private.current_user_role() returns public.app_role language sql stable security definer as $$select role from public.profiles where id=auth.uid()$$;
    grant usage on schema public,auth,private to authenticated;
    grant select on all tables in schema public to authenticated;
  `);
  for(const name of Object.keys(ids))await db.query('insert into public.profiles(id,role,registration_status) values($1,$2,$3)',[ids[name],name==='admin'?'admin':['counselor','otherCounselor','unapproved'].includes(name)?'counselor':'student',name==='active'?'active':['withReceipt','missingReceipt'].includes(name)?'pending':'incomplete']);
  await db.query("insert into public.counselor_profiles values($1,'approved'),($2,'approved'),($3,'pending')",[ids.counselor,ids.otherCounselor,ids.unapproved]);
  for(const name of ['withReceipt','manual','missingReceipt','unverified','active','otherStudent']){
    await db.query('insert into auth.users(id,phone_confirmed_at) values($1,$2)',[ids[name],name==='unverified'?null:new Date()]);
  }
  await db.query('insert into public.student_registrations(student_id,receipt_path) values($1,$2),($3,$4)',[ids.withReceipt,`${ids.withReceipt}/receipt.png`,ids.missingReceipt,`${ids.missingReceipt}/receipt.png`]);
  await db.query("insert into storage.objects(bucket_id,name) values('registration-receipts',$1)",[`${ids.withReceipt}/receipt.png`]);
  await db.query('insert into public.student_account_details(student_id) values($1),($2),($3)',[ids.manual,ids.unverified,ids.withReceipt]);
  const read=name=>readFileSync(`supabase/migrations/${name}`,'utf8');
  await db.exec(read('053_prevent_counselor_reassignment.sql'));
  await db.exec(read('064_assignment_activates_student.sql'));
  await db.exec(read('093_auto_student_activation_by_receipt.sql'));
  const actor=async name=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[ids[name]]);await db.exec('set role authenticated');};
  const activate=(name,expected,counselor='counselor')=>db.query('select public.admin_activate_student_auto($1,$2,$3)',[ids[name],ids[counselor],expected]);
  const assign=name=>db.query('select public.admin_assign_student_counselor($1,$2)',[ids[name],ids.counselor]);
  const status=async name=>(await db.query('select registration_status from public.profiles where id=$1',[ids[name]])).rows[0].registration_status;
  await actor('admin');
  await assert.rejects(assign('withReceipt'),/Only an already active student/);
  await assert.rejects(assign('manual'),/Only an already active student/);
  await assert.rejects(activate('withReceipt',null),/Receipt changed/);
  await assert.rejects(activate('withReceipt',`${ids.withReceipt}/replaced.png`),/Receipt changed/);
  await assert.rejects(activate('missingReceipt',`${ids.missingReceipt}/receipt.png`),/Complete current registration and receipt required/);
  await assert.rejects(activate('withReceipt',`${ids.withReceipt}/receipt.png`,'unapproved'),/Approved counselor required/);
  await assert.rejects(db.query('select public.admin_activate_student_without_receipt($1,$2)',[ids.withReceipt,ids.counselor]),/Submitted receipt must be reviewed/);
  assert.equal(await status('withReceipt'),'pending');
  assert.equal((await db.query('select count(*)::int as n from public.student_manual_activations')).rows[0].n,0);
  await activate('withReceipt',`${ids.withReceipt}/receipt.png`);
  assert.equal(await status('withReceipt'),'active');
  assert.equal((await db.query('select approved_by from public.student_registrations where student_id=$1',[ids.withReceipt])).rows[0].approved_by,ids.admin);
  assert.equal((await db.query('select count(*)::int as n from public.student_manual_activations')).rows[0].n,0,'receipt approval does not log a manual exception');
  await assert.rejects(activate('unverified',null),/Confirmed student required/);
  await activate('manual',null);
  assert.equal(await status('manual'),'active');
  assert.equal((await db.query('select previous_status,activated_by from public.student_manual_activations where student_id=$1',[ids.manual])).rows[0].activated_by,ids.admin);
  await assign('active');
  assert.equal(await status('active'),'active');
  assert.equal((await db.query('select count(*)::int as n from public.student_manual_activations')).rows[0].n,1,'active-only assignment does not create manual activation');
  await assert.rejects(assign('active'),/already has a counselor/);
  await assert.rejects(activate('manual',null),/Inactive student required/);
  await actor('otherStudent');
  await assert.rejects(activate('unverified',null),/Admin only/);
  await assert.rejects(assign('otherStudent'),/Admin only/);
  await db.exec('reset role; set role anon');
  await assert.rejects(activate('unverified',null),/permission denied/);
  await db.close();
  console.log('PASS: receipt routed to audited receipt approval; no-receipt to manual audit; stale/missing receipts, inactive direct assignment and non-admin callers rejected');
})().catch(error=>{console.error(error);process.exitCode=1});
