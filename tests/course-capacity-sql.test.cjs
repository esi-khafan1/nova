const assert = require('node:assert/strict');
const fs = require('node:fs');
const {PGlite} = require('@electric-sql/pglite');
(async () => {
 const db = new PGlite();
 await db.exec(`create role anon; create role authenticated; create role service_role;
 create schema private; create schema auth; create schema storage;
 create function private.is_super_admin() returns boolean language sql stable as $$select current_setting('test.super',true)='yes'$$;
 create function auth.uid() returns uuid language sql stable as $$select 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa'::uuid$$;
 create function storage.foldername(text) returns text[] language sql immutable as $$select string_to_array($1,'/')$$;
 create table public.profiles(id uuid, role text, registration_status text);
 insert into public.profiles values ('aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa','student','pending');
 create table storage.objects(bucket_id text, name text); alter table storage.objects enable row level security;
 grant usage on schema public, auth, storage to anon,authenticated;
 grant select on public.profiles to authenticated; grant insert,select on storage.objects to authenticated;
 create policy receipt_upload_own_pending on storage.objects for insert to authenticated with check (true);
 create policy admin_upload_test on storage.objects for insert to authenticated with check (current_setting('test.admin',true)='yes');
 create table private.submissions(value jsonb);
 create function public.submit_student_registration(payload jsonb) returns void language plpgsql security definer set search_path='' as $$begin insert into private.submissions values(payload); end$$;
 revoke all on function public.submit_student_registration(jsonb) from public,anon; grant execute on function public.submit_student_registration(jsonb) to authenticated;
 `);
 await db.exec(fs.readFileSync('supabase/migrations/110_super_admin_course_settings.sql','utf8'));
 await db.exec(fs.readFileSync('supabase/migrations/116_course_capacity_closed.sql','utf8'));
 let offers=(await db.query('select * from public.get_course_offer_settings_v2()')).rows;
 assert.equal(offers.length,8); assert.ok(offers.every(x=>!x.sold_out && !x.reservation));
 await db.exec('set role anon');
 assert.equal((await db.query('select count(*)::int n from public.get_course_offer_settings_v2()')).rows[0].n,8);
 await assert.rejects(db.query("select public.super_admin_set_course_status('sold_out')"),/permission denied/);
 await assert.rejects(db.query("select public.submit_student_registration('{}')"),/permission denied/);
 await db.exec("reset role; set role authenticated; select set_config('test.super','no',false)");
 await assert.rejects(db.query("select public.super_admin_set_course_status('sold_out')"),/Super admin only/);
 await db.query("select public.submit_student_registration('{\"before\":true}')");
 await db.query("insert into storage.objects values ('registration-receipts','aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa/before.jpg')");
 await db.exec("select set_config('test.super','yes',false)");
 await assert.rejects(db.query("select public.super_admin_set_course_status('invalid')"),/Invalid status/);
 await db.query("select public.super_admin_set_course_status('sold_out')");
 offers=(await db.query('select * from public.get_course_offer_settings_v2()')).rows;
 assert.ok(offers.every(x=>x.sold_out && !x.reservation));
 assert.equal((await db.query('select public.course_enrollment_open() open')).rows[0].open,false);
 await assert.rejects(db.query("select public.submit_student_registration('{\"stale\":true}')"),/Course capacity full/);
 await assert.rejects(db.query("select private.submit_student_registration('{}')"),/permission denied/);
 await assert.rejects(db.query("insert into storage.objects values ('registration-receipts','aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa/closed.jpg')"),/row-level security/);
 await db.exec("select set_config('test.admin','yes',false)");
 await db.query("insert into storage.objects values ('registration-receipts','aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa/admin.jpg')");
 await db.exec("select set_config('test.admin','no',false)");
 await db.query("select public.super_admin_set_course_status('reservation')");
 assert.ok((await db.query('select * from public.get_course_offer_settings_v2()')).rows.every(x=>x.reservation&&!x.sold_out));
 await db.query("select public.submit_student_registration('{\"after\":true}')");
 await db.query("select public.super_admin_set_course_status('sold_out')");
 await db.query('select public.super_admin_set_course_reservation(false)');
 assert.ok((await db.query('select * from public.get_course_offer_settings_v2()')).rows.every(x=>!x.sold_out&&!x.reservation));
 await db.exec('reset role');
 assert.equal((await db.query('select count(*)::int n from private.submissions')).rows[0].n,2);
 await db.close();
 console.log('PASS: sold-out status, authorization, stale submissions, own receipt blocking, admin uploads and reopening');
})().catch(e=>{console.error(e);process.exitCode=1});
