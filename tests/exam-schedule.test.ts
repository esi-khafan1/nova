import assert from "node:assert/strict";
import { earliestExamSchedule, tehranDateTime, validWindowEnd, timeAfter, clampExamTime } from "../lib/exam-schedule";
import { readFileSync } from "node:fs";
assert.deepEqual(tehranDateTime(new Date("2026-10-15T07:33:27Z")), { date: "2026-10-15", time: "11:03" });
assert.deepEqual(earliestExamSchedule(new Date("2026-10-15T07:33:27Z")), { today: "2026-10-15", date: "2026-10-15", time: "11:09" });
assert.equal(earliestExamSchedule(new Date("2026-10-15T07:30:00Z")).time, "11:05");
assert.deepEqual(earliestExamSchedule(new Date("2026-10-15T20:27:10Z")), { today: "2026-10-15", date: "2026-10-16", time: "00:03" });
assert.deepEqual(earliestExamSchedule(new Date("2026-10-15T21:00:00Z")), { today: "2026-10-16", date: "2026-10-16", time: "00:35" });
assert.equal(validWindowEnd("13:07", "12:00"), "14:07");
assert.equal(validWindowEnd("11:09", "12:00"), "12:00");
assert.equal(validWindowEnd("23:45", "12:00"), "23:59");
assert.equal(timeAfter("23:59", 1), null);
assert.equal(timeAfter("11:09", 1), "11:10");
assert.equal(clampExamTime("11:00", "11:07"), "11:07");
assert.equal(clampExamTime("14:00", "11:07"), "14:00");
assert.equal(clampExamTime("09:00"), "09:00");
const builder = readFileSync("components/dashboard/exam-builder.tsx", "utf8");
assert.ok(builder.includes("onChange={changeScheduledDate}"));
assert.ok(builder.includes("setScheduledTime(bounds.time)"));
assert.ok(!builder.includes("toTimeString()"));
assert.ok(builder.includes('window.setInterval(refresh, 15000)'));
assert.ok(builder.includes('timeAfter(scheduledTime, 1)'));
console.log("Tehran schedule: first allowed exact minute, rounding, UTC/date rollover, late-night limit, floating end and minimum-time clamping passed.");
